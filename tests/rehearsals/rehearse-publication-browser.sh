#!/bin/sh

#=======================# Migrated publication acceptance #=======================#
# Reuse the current Compose project. A generated test database is separate from
# retained records; temporary browser sessions never enter retained artifacts.

#=======================# VARIABLES #=======================#
set -eu
umask 077
repository_root=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
work_directory=$(mktemp -d "${TMPDIR:-/tmp}/tekdocs-publication-browser.XXXXXX")
export TEKDOCS_PUBLICATION_ACCEPTANCE_DIRECTORY="$work_directory"
TEKDOCS_PUBLICATION_ACCEPTANCE_DATABASE="td_pub_$(python3 -c 'import secrets; print(secrets.token_hex(6))')"
export TEKDOCS_PUBLICATION_ACCEPTANCE_DATABASE
pytest_pid=""
restore_services=false
frontend_was_running=false
safe_summary="$repository_root/artifacts/playwright-safe/publication-live.json"

#======================# FUNCTIONS #=======================#
acceptance_compose() {
  docker compose -f "$repository_root/compose.yml" -f "$repository_root/compose.publication-browser.yml" "$@"
}

mark_browser_failed() {
  printf '%s\n' '{"status":"failed"}' > "$work_directory/browser-finished.partial"
  chmod 0640 "$work_directory/browser-finished.partial"
  mv -f "$work_directory/browser-finished.partial" "$work_directory/browser-finished.json"
}

cleanup() {
  status=$?
  trap - EXIT HUP INT TERM
  if [ -n "$pytest_pid" ]; then
    mark_browser_failed
    # Prefer normal fixture teardown; interrupt only this run's pytest if it
    # is still initializing its database and cannot see the browser marker.
    for attempt in $(seq 1 5); do
      kill -0 "$pytest_pid" 2>/dev/null || break
      sleep 1
    done
    if kill -0 "$pytest_pid" 2>/dev/null; then
      acceptance_compose exec -T migrate sh -c '
        test -f /acceptance/server.pid || exit 0
        read -r runner_pid < /acceptance/server.pid
        case "$runner_pid" in ""|*[!0-9]*) exit 1 ;; esac
        kill -INT "$runner_pid"
      ' >/dev/null 2>&1 || true
      for attempt in $(seq 1 15); do
        kill -0 "$pytest_pid" 2>/dev/null || break
        sleep 1
      done
    fi
  fi
  if [ "$restore_services" = true ]; then
    acceptance_compose stop frontend migrate >/dev/null 2>&1 || true
    if [ -n "$pytest_pid" ]; then wait "$pytest_pid" || true; fi
    # Django cannot always drop a partly initialized database after interruption.
    # This name is generated by this invocation, never supplied by an operator.
    case "$TEKDOCS_PUBLICATION_ACCEPTANCE_DATABASE" in td_pub_????????????) ;; *) exit 1 ;; esac
    docker compose -f "$repository_root/compose.yml" exec -T db sh -c '
      case "$1" in *[!a-z0-9_]*) exit 1 ;; esac
      psql -U "$POSTGRES_USER" -d postgres -v ON_ERROR_STOP=1 -q \
        -c "DROP DATABASE IF EXISTS \"test_$1\" WITH (FORCE)"
    ' sh "$TEKDOCS_PUBLICATION_ACCEPTANCE_DATABASE" >/dev/null || status=1
    docker compose -f "$repository_root/compose.yml" up --no-start --no-deps --no-build frontend migrate >/dev/null 2>&1 || true
    if [ "$frontend_was_running" = true ]; then
      docker compose -f "$repository_root/compose.yml" start frontend >/dev/null 2>&1 || true
    fi
  fi
  if [ "$status" -ne 0 ] && [ -f "$work_directory/server.log" ]; then
    tail -60 "$work_directory/server.log" >&2
  fi
  rm -rf "$work_directory"
  exit "$status"
}

#=========================# MAIN #==========================#
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' HUP TERM
cd "$repository_root"
rm -f "$safe_summary"
if docker compose ps --status running --services | grep -qx migrate; then
  echo "The migrate service must be idle before publication browser acceptance." >&2
  exit 1
fi
if docker compose ps --status running --services | grep -qx frontend; then frontend_was_running=true; fi
docker compose up -d --wait db
restore_services=true
acceptance_compose up -d --no-deps --build migrate frontend
# Linux bind mounts retain the controller's host UID. Keep that owner and grant
# only the image's service group access; secret session inputs still use 0600.
acceptance_compose exec -T --user 0:0 migrate sh -c \
  'chgrp "$(id -g tekdocs)" /acceptance; chmod 2770 /acceptance'
acceptance_compose exec -T migrate sh -c \
  'printf "%s\n" "$$" > /acceptance/server.pid; exec pytest "$@"' sh apps/core/tests/test_publication_browser_acceptance.py \
  --liveserver=0.0.0.0:8081 --tb=short -q > "$work_directory/server.log" 2>&1 &
pytest_pid=$!
ready=false
for attempt in $(seq 1 240); do
  if [ -f "$work_directory/ready.json" ]; then ready=true; break; fi
  if ! kill -0 "$pytest_pid" 2>/dev/null; then break; fi
  sleep 1
done
[ "$ready" = true ] || { echo "Publication acceptance server did not become ready." >&2; exit 1; }
browser_status=0
acceptance_compose exec -T frontend npx playwright test --config=playwright.publication-live.config.ts || browser_status=$?
if [ "$browser_status" -ne 0 ]; then
  mark_browser_failed
fi
# Only this value-free reporter output may be read by the host controller.
acceptance_compose exec -T frontend sh -c \
  'test ! -f /acceptance/browser-summary.json || chmod 0644 /acceptance/browser-summary.json'
server_status=0
wait "$pytest_pid" || server_status=$?
pytest_pid=""
python3 - "$work_directory" "$server_status" <<'PY'
import json
import sys
from pathlib import Path
directory = Path(sys.argv[1])
report = json.loads((directory / "browser-summary.json").read_text())
report["server_verification"] = "passed" if sys.argv[2] == "0" else "failed"
if sys.argv[2] != "0":
    report["status"] = "failed"
(directory / "combined-summary.json").write_text(json.dumps(report, indent=2) + "\n")
PY
"$repository_root/scripts/check-browser-artifacts.sh" "$work_directory/combined-summary.json"
mkdir -p "$(dirname "$safe_summary")"
cp "$work_directory/combined-summary.json" "$safe_summary"
[ "$browser_status" -eq 0 ] && [ "$server_status" -eq 0 ] || exit 1
echo "Real migrated-publication browser journey, retained bytes and authority round-trip passed."
